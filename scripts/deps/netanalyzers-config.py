"""Write deps/analyzers/netanalyzers-all.globalconfig, the rules that AnalysisMode=All turns on, for the
Microsoft.CodeAnalysis.NetAnalyzers version that Directory.Build.props pins.

An SDK-style project gets this list from the .NET SDK (analysislevel_<n>_all.globalconfig). The old-style
csproj projects here don't, and the NuGet package doesn't carry it; it does carry every rule in
documentation/Microsoft.CodeAnalysis.NetAnalyzers.sarif. The SDK's list is the rules tagged
EnabledRuleInAggressiveMode, each as a warning (checked against SDK 9.0.318's list: the same rules, plus five
that are new in 10.0), so this writes that from the package that NuGet restored.

Run it after changing the package version (restore first); --check only compares, for CI.

usage: python -X utf8 scripts/deps/netanalyzers-config.py [--check]
"""
import json, os, pathlib, re, sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
PROPS = ROOT / 'Directory.Build.props'
OUT = ROOT / 'deps' / 'analyzers' / 'netanalyzers-all.globalconfig'
PACKAGE = 'Microsoft.CodeAnalysis.NetAnalyzers'


def pinned_version():
    m = re.search(r'<PackageReference Include="' + re.escape(PACKAGE) + r'" Version="([^"]+)"', PROPS.read_text(encoding='utf-8'))
    if not m:
        raise SystemExit(f'{PROPS.name}: no PackageReference to {PACKAGE}')
    return m.group(1)


def sarif(version):
    cache = pathlib.Path(os.environ.get('NUGET_PACKAGES') or pathlib.Path.home() / '.nuget' / 'packages')
    path = cache / PACKAGE.lower() / version / 'documentation' / f'{PACKAGE}.sarif'
    if not path.is_file():
        raise SystemExit(f'{path} not found: restore a project first (msbuild -t:Restore)')
    return json.loads(path.read_text(encoding='utf-8-sig'))


def config(version):
    rules = {}
    for run in sarif(version)['runs']:
        # runs: the rules of both languages, the C# ones, the Visual Basic ones (left out)
        if run['tool']['name'] in (PACKAGE, PACKAGE.replace('CodeAnalysis.', 'CodeAnalysis.CSharp.')):
            for rule_id, rule in run['rules'].items():
                if 'EnabledRuleInAggressiveMode' in rule['properties'].get('tags', []):
                    rules[rule_id] = rule['shortDescription']
    lines = [
        f'# Generated by scripts/deps/netanalyzers-config.py from {PACKAGE} {version}: the rules that',
        '# AnalysisMode=All turns on, as the .NET SDK lists them for SDK-style projects. Do not edit; change the',
        '# severity of a rule in .editorconfig, which takes precedence over this file.',
        '',
        'is_global = true',
        'global_level = -100',
    ]
    for rule_id in sorted(rules):
        lines += ['', f'# {rule_id}: {rules[rule_id]}', f'dotnet_diagnostic.{rule_id}.severity = warning']
    return '\n'.join(lines) + '\n', len(rules)


def main():
    version = pinned_version()
    text, count = config(version)
    if '--check' in sys.argv[1:]:
        # a checkout may have turned the line ends into CRLF
        if not OUT.is_file() or OUT.read_bytes().replace(b'\r\n', b'\n') != text.encode('utf-8'):
            raise SystemExit(f'{OUT.relative_to(ROOT)} is not the list for {PACKAGE} {version}: run scripts/deps/netanalyzers-config.py')
        print(f'{OUT.relative_to(ROOT)}: {count} rules, matches {PACKAGE} {version}')
        return
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_bytes(text.encode('utf-8'))
    print(f'wrote {OUT.relative_to(ROOT)}: {count} rules from {PACKAGE} {version}')


if __name__ == '__main__':
    main()
